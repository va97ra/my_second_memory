/// Расчёты вентиляции.
///
/// «Сколько воздуха нужно помещению» — один расчёт с тремя основаниями, а
/// не три отдельных: вопрос у человека один, а кратность, люди и площадь —
/// три способа на него ответить.
enum VentilationMode { duct, room, heater }

/// От чего считать потребность помещения в воздухе.
enum RoomAirBasis { changes, people, area }
