HH_NAME = {
    'Библиотека имени Ленина': 'Библиотека им.Ленина',
    'Новомосковская': 'Новомосковская (Коммунарка)',
    'Выставочная': 'Деловой центр (Выставочная)',
}


def norm(s):
    return s.lower().replace('ё', 'е').replace('-', ' ').strip()


hh = json.load(open(os.path.join(HERE, 'hh_metro.json'), encoding='utf-8'))
coords = {}   # (hh line id, norm name) -> (lat, lng)
anyline = {}
for l in hh['lines']:
    for s in l['stations']:
        coords[(l['id'], norm(s['name']))] = (s['lat'], s['lng'])
        anyline.setdefault(norm(s['name']), (s['lat'], s['lng']))


def dist(a, b):
    la1, lo1 = map(math.radians, a)
    la2, lo2 = map(math.radians, b)
    x = (lo2 - lo1) * math.cos((la1 + la2) / 2)
    y = la2 - la1
    return math.hypot(x, y) * 6371000


stations = []  # (line id, name, lat, lng)
index = {}
missing = []
for lid, num, lname, color, hexc, circle, hhid, branches in LINES:
    for br in branches:
        for name in br:
            if (lid, name) in index:
                continue
            key = norm(HH_NAME.get(name, name))
            c = coords.get((hhid, key)) or anyline.get(key)
            if c is None:
                missing.append((lid, name))
                c = (0.0, 0.0)
            index[(lid, name)] = len(stations)
            stations.append((lid, name, c[0], c[1]))

if missing:
    print('НЕТ КООРДИНАТ:', missing)

# Пересадки: одно имя — всегда; разные имена — если ближе 600 м.
transfers = []
for i, a in enumerate(stations):
    for j in range(i + 1, len(stations)):
        b = stations[j]
        if a[0] == b[0] or a[2] == 0 or b[2] == 0:
            continue
        d = dist(a[2:], b[2:])
        same = norm(a[1]) == norm(b[1])
        if same or d < 600:
            transfers.append((i, j, round(d)))

if '--review' in sys.argv:
    for i, j, d in transfers:
        a, b = stations[i], stations[j]
        flag = '' if norm(a[1]) == norm(b[1]) else '   <-- разные имена'
        print(f'{a[0]:>3} {a[1]:<28} {b[0]:>3} {b[1]:<28} {d:>5} м{flag}')
    sys.exit()

EXCLUDE = set()
ADD = []
try:
    exec(open(os.path.join(HERE, 'metro_fix.py'), encoding='utf-8').read())
except FileNotFoundError:
    pass
transfers = [t for t in transfers if (stations[t[0]][0], stations[t[0]][1], stations[t[1]][0], stations[t[1]][1]) not in EXCLUDE]
for an, al, bn, bl in ADD:
    i, j = index[(al, an)], index[(bl, bn)]
    transfers.append((i, j, round(dist(stations[i][2:], stations[j][2:]))))


def dq(s):
    return "'" + s.replace("'", "\\'") + "'"


