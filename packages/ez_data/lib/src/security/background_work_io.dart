import 'dart:async';
import 'dart:isolate';

/// Выполняет тяжёлую работу в отдельном изоляте, чтобы главный поток
/// продолжал рисовать.
///
/// [work] уезжает в изолят копией вместе со всем, что захватил, поэтому
/// захватывать можно только данные, а не объекты с состоянием.
Future<R> inBackground<R>(FutureOr<R> Function() work) => Isolate.run(work);
