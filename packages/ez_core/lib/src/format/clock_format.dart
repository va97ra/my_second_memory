/// Время суток, заданное числом минут от полуночи, в виде `ЧЧ:ММ`.
///
/// Формат одинаков для всех языков: часы и минуты по 24-часовым часам,
/// ведущий ноль обязателен. Формула живёт здесь одна на всё приложение — до
/// этого она была записана дважды, в записях и в графиках смен, и правка в
/// одной копии не доходила до другой.
String formatMinutesOfDay(int minutes) {
  final hours = (minutes ~/ 60).toString().padLeft(2, '0');
  final rest = (minutes % 60).toString().padLeft(2, '0');
  return '$hours:$rest';
}
